/* skembed: data/soccerkid.dat as a C array for the soccerkid program (an empty one when the file is missing). The output is
   rewritten only when it would change, so an unchanged archive does not rebuild the program. Build tool, no game logic. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static unsigned char *read_all(const char *path, size_t *n) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    size_t cap = 1 << 20, len = 0;
    unsigned char *b = malloc(cap);
    for (size_t r; b && (r = fread(b + len, 1, cap - len, f)) > 0; ) {
        len += r;
        if (len == cap) { unsigned char *g = realloc(b, cap *= 2); if (!g) { free(b); b = NULL; } else b = g; }
    }
    fclose(f);
    *n = len;
    return b;
}

int main(int argc, char **argv) {
    if (argc != 3) { fprintf(stderr, "usage: skembed <soccerkid.dat> <out.c>\n"); return 2; }
    size_t n = 0;
    unsigned char *d = read_all(argv[1], &n);
    size_t cap = 256 + n * 5 + n / 16 + 64, len = 0;
    char *c = malloc(cap);
    if (!c) return 1;
    len += (size_t)snprintf(c + len, cap - len, "/* generated by skembed from %s: do not edit */\n#include <stddef.h>\n"
                            "const size_t sk_embedded_size = %zu;\nconst unsigned char sk_embedded_data[%zu] = {", d ? "soccerkid.dat" : "nothing", n, n ? n : 1);
    for (size_t i = 0; i < n; i++) len += (size_t)snprintf(c + len, cap - len, "%s%u,", i % 24 ? "" : "\n", d[i]);
    if (!n) len += (size_t)snprintf(c + len, cap - len, "0");
    len += (size_t)snprintf(c + len, cap - len, "\n};\n");
    size_t old_n = 0;
    unsigned char *old = read_all(argv[2], &old_n);
    int rc = 0;
    if (!old || old_n != len || memcmp(old, c, len) != 0) {
        FILE *f = fopen(argv[2], "wb");
        if (!f || fwrite(c, 1, len, f) != len) rc = 1;
        if (f && fclose(f) != 0) rc = 1;
        if (rc) fprintf(stderr, "skembed: could not write %s\n", argv[2]);
    }
    free(old); free(c); free(d);
    return rc;
}
